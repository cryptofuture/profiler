export function translateAnswer (locale, answer) {
  return answerCopy[locale]?.[answer] || answer
}

export function translateRole (locale, role) {
  return roleCopy[locale]?.[role] || role
}

export function translateSkill (locale, skillId) {
  return skillCopy[locale]?.[skillId] || skillId.replace(/([A-Z])/g, ' $1').replace(/^./, letter => letter.toUpperCase())
}

export function translate (locale, key, values = {}) {
  const dictionary = translations[locale] || translations.en
  const value = dictionary[key] ?? translations.en[key] ?? key
  if (Array.isArray(value)) return value
  return String(value).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`)
}
